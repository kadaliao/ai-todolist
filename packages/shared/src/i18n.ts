export type Locale = 'zh' | 'en';

const dicts: Record<Locale, Record<MessageKey, string>> = { zh, en };

export function detectLocale(): Locale {
  const lang = (typeof navigator !== 'undefined' && navigator.language) || 'zh-CN';
  return lang.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let current: Locale = detectLocale();

export function setLocale(l: Locale): void {
  current = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
}

export function getLocale(): Locale {
  return current;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? zh[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
